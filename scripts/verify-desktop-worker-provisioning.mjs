import fs from 'node:fs';
const source = fs.readFileSync(new URL('../api/desktop/worker-provision.ts', import.meta.url), 'utf8');
const fail = (message) => { console.error(message); process.exit(1); };
if (!source.includes('DESKTOP_WORKER_PROVISIONING_ENABLED')) fail('Provisionamento desktop nao e fail-closed.');
if (!source.includes('DESKTOP_WORKER_PROVISIONING_ALLOWED_EMAILS')) fail('Allowlist de email ausente.');
if (!source.includes('SUPABASE_SERVICE_ROLE_KEY')) fail('Credencial server-side nao e lida pelo endpoint.');
if (!source.includes('DESKTOP_CLOUDFLARE_TUNNEL_TOKEN')) fail('Token do Cloudflare Tunnel nao e lido pelo endpoint.');
if (!source.includes("crypto.subtle.encrypt")) fail('Credenciais nao sao cifradas para o dispositivo.');
if (!source.includes("RSA-OAEP")) fail('RSA-OAEP ausente.');
if (!source.includes('auth.getUser(token)')) fail('Endpoint nao valida sessao do usuario.');
const response = source.split('return send(res, 200')[1] ?? '';
if (/serviceRoleKey\s*[,}]/.test(response)) fail('Service Role parece retornar em texto claro.');
if (/cloudflareTunnelToken\s*[,}]/.test(response)) fail('Tunnel token parece retornar em texto claro.');
if (!response.includes('encryptedCloudflareTunnelToken')) fail('Tunnel token cifrado nao e retornado.');
console.log('OK: provisionamento desktop autentica, aplica allowlist e cifra Service Role + Cloudflare Tunnel token.');
