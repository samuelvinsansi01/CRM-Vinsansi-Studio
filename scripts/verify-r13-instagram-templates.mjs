import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const root=path.resolve(fileURLToPath(new URL('..',import.meta.url)));
const read=(rel)=>fs.readFileSync(path.join(root,rel),'utf8');
const contract=read('src/services/templates/templateContract.ts');
const selector=read('src/services/templates/templateSelector.ts');
const prep=read('src/services/queue-preparation/queuePreparation.service.ts');
const repo=read('src/repositories/config/canonicalConfig.repository.ts');
const page=read('src/pages/ConfigTablePage.tsx');
const drawer=read('src/components/ApprovedLeadsQueueDrawer.tsx');
const toolManifest=JSON.parse(read('public/tools/manifest.json'));
assert.ok(contract.includes("channel !== 'Instagram'"));
assert.ok(contract.includes('As mensagens do Instagram devem ser preenchidas em sequência'));
