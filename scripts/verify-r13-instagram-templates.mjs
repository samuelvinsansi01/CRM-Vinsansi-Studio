assert.ok(page.includes('Instagram: obrigatória. Mensagens 2 a 4 são opcionais'));
assert.ok(drawer.includes('{lead.blockReason ? <div'));
const instagram=toolManifest.tools.find((tool)=>tool.id==='instagram-extension');
assert.equal(instagram?.version,'2.0.1');
assert.ok(fs.existsSync(path.join(root,'public/tools/instagram-extension-latest.zip')));
const patch=read('PATCH-CORRETIVO-CRM-2.4.0-R13.sql');
assert.ok(patch.includes("latest_version = '2.0.1'"));
