import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname,join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root=dirname(dirname(fileURLToPath(import.meta.url)));
const workspace=dirname(root);
const read=path=>readFileSync(join(root,path),'utf8');
const schema=JSON.parse(JSON.parse(readFileSync(join(workspace,'Banco - Atual.txt'),'utf8'))[0].database_schema_snapshot);
const migration=read('supabase/migrations/20260825203000_r22_current_tool_installation_lifecycle.sql');
const executor=read('server/tools/executor.ts');
const browserPair=read('server/routes/tools/browser-pair.ts');
const maps=read('server/maps/shared.ts');
const managerConfig=readFileSync(join(workspace,'CRM - Gerenciador de Disparos/src/main/config/SecureConfigService.ts'),'utf8');
const worker=readFileSync(join(workspace,'CRM - Worker/src/worker.js'),'utf8');
let checks=0;const ok=(condition,message)=>{checks+=1;assert.ok(condition,message);};

ok(!schema.columns.some(c=>c.table==='organization_tool_installations'&&c.column==='is_current'),'snapshot fonte já contém coluna posterior ao R22');
for(const token of ['operational_slot','is_current','superseded_at','superseded_by_installation_id'])ok(migration.includes(token),`lifecycle sem ${token}`);
ok(migration.includes('row_number() OVER'),'backfill não ranqueia instalações históricas');
ok(migration.includes('coalesce(i.last_seen_at'),'backfill não prioriza heartbeat real');
ok(migration.includes('organization_tool_installations_one_current_slot_idx'),'corrida pode criar dois atuais no mesmo slot');
ok(migration.includes('pg_advisory_xact_lock'),'registro concorrente sem serialização por slot');
ok(migration.includes("logout_reason=coalesce(s.logout_reason,'installation_superseded')"),'sessão histórica não é revogada');
ok(migration.includes('AND i.is_current'),'health/heartbeat não filtra instalação corrente');
ok(migration.includes("'historical'"),'health não expõe inventário histórico separado');
ok(migration.includes("i.tool_id IN('vinsansi_capture','vinsansi_instagram','vinsansi_whatsapp_manager')"),'alerta não cobre as três ferramentas locais');
ok(migration.includes("ON CONFLICT(organizations_id,alert_key)"),'deduplicação R21 removida');
ok(migration.includes("alert_key='tool_installation_stale'"),'resolução de alerta stale removida');
ok(migration.includes('h.organization_tool_installations_id IS NULL OR EXISTS'),'componentes históricos ainda aparecem no health');
ok(executor.includes("installation.is_current!==true"),'credencial/sessão de instalação substituída aceita');
ok(executor.includes('metadata?:unknown'),'registro não recebe metadado de slot');
ok(browserPair.includes('capabilities:current.data.requested_capabilities,metadata}'),'browser pairing perde metadado antes do registro');
ok(maps.includes("canonical.is_current!==true"),'rota Captura aceita sessão histórica');
ok(migration.includes("p_tool_id='vinsansi_instagram'"),'slot Instagram não deriva do perfil existente');
ok(migration.includes("ELSE 'primary'"),'Captura/Gerenciador não recebem slot primário');
for(const version of ['3.11.0','3.12.0','3.13.0','3.13.1'])ok(managerConfig.includes(`dispatch-worker:${version}`),`Gerenciador não migra Worker ${version}`);
ok(managerConfig.includes("workerImage: 'vinsansi/dispatch-worker:3.13.2'"),'alvo canônico do Worker não é 3.13.2');
ok(worker.includes("const VERSION = '3.13.2'"),'fonte canônica do processo Worker não reporta 3.13.2');
console.log(`Etapa 11 R22 contratos: PASS (${checks} verificações)`);
