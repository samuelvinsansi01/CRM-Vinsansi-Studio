import fs from 'node:fs';
import crypto from 'node:crypto';
const root=new URL('../',import.meta.url);
const read=(p)=>fs.readFileSync(new URL(p,root),'utf8');
const manifest=JSON.parse(read('supabase/baseline/manifest.json'));
const full=read('supabase/baseline/bootstrap_full.sql');
const base=read('supabase/baseline/00000000000000_base_public_schema.sql');
const migration=read('supabase/migrations/20260802160000_schema_release_manifest.sql');
const hash=crypto.createHash('sha256').update(full).digest('hex');
if(hash!==manifest.bootstrapSha256) throw new Error('baseline_hash_mismatch');
const baseHash=crypto.createHash('sha256').update(base).digest('hex');
if(baseHash!==manifest.baseSha256) throw new Error('baseline_base_hash_mismatch');
if(!migration.includes(manifest.baseSha256)) throw new Error('baseline_release_hash_not_registered');
if(manifest.baseTables<25) throw new Error('baseline_base_tables_incomplete');
for(const table of ['leads','queues','queue_items','sents','instances','apify_accounts']) if(!base.includes(`public.${table}`)) throw new Error(`baseline_table_missing:${table}`);
for(const file of manifest.migrations) if(!full.includes(`-- >>> ${file}`)) throw new Error(`baseline_migration_missing:${file}`);
for(const token of ['platform_schema_releases','platform_schema_health']) if(!migration.includes(token)) throw new Error(`schema_manifest_missing:${token}`);
console.log(`Database baseline: OK (${manifest.baseTables} base tables, ${manifest.migrations.length} migrations, ${hash.slice(0,12)}…).`);
