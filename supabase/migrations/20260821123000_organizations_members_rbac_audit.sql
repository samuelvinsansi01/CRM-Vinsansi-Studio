CREATE OR REPLACE FUNCTION public.validate_real_user_auth_reference()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public, auth
AS $$
BEGIN
  IF coalesce(NEW.users_is_scope,false)=false
     AND NOT EXISTS(SELECT 1 FROM auth.users au WHERE au.id=NEW.auth_user_id) THEN
    RAISE EXCEPTION 'real_user_requires_auth_account';
  END IF;
  RETURN NEW;
END;
$$;
