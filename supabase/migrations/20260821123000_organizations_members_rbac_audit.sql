CREATE OR REPLACE FUNCTION public.transfer_organization_ownership(p_target_member_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_org bigint:=public.current_organization_id();
  v_actor bigint:=public.current_actor_user_id();
  v_current_owner bigint;
  v_gestor_role bigint;
BEGIN
  IF NOT (public.is_platform_owner() OR public.current_access_level()='owner') THEN RAISE EXCEPTION 'permission_denied:organization.ownership.transfer'; END IF;
  SELECT organization_members_id INTO v_current_owner FROM public.organization_members WHERE organizations_id=v_org AND access_level='owner' AND status_id=1;
  IF NOT EXISTS(SELECT 1 FROM public.organization_members WHERE organization_members_id=p_target_member_id AND organizations_id=v_org AND status_id=1) THEN RAISE EXCEPTION 'target_member_not_available'; END IF;
  IF p_target_member_id=v_current_owner THEN RETURN; END IF;
  SELECT organization_roles_id INTO v_gestor_role FROM public.organization_roles WHERE organizations_id=v_org AND organization_roles_key='gestor';

  -- Evita colisão com o índice de Dono único durante a transição. Se o Dono
  -- anterior for o Platform Owner, ele sai da associação operacional e continua
  -- acessando a empresa somente em modo administrativo global.
  IF EXISTS(
    SELECT 1 FROM public.organization_members om
    JOIN public.platform_owners po ON po.users_id=om.users_id
    WHERE om.organization_members_id=v_current_owner
  ) THEN
    UPDATE public.organization_members
       SET access_level='member',organization_roles_id=NULL,status_id=2,deactivated_at=now(),organization_members_updated_at=now()
     WHERE organization_members_id=v_current_owner;
  ELSE
    UPDATE public.organization_members
       SET access_level='manager',organization_roles_id=coalesce(organization_roles_id,v_gestor_role),organization_members_updated_at=now()
     WHERE organization_members_id=v_current_owner;
  END IF;
  UPDATE public.organization_members SET access_level='owner',organization_roles_id=NULL,organization_members_updated_at=now() WHERE organization_members_id=p_target_member_id;

  PERFORM public.append_audit_event('organization','ownership_transferred','organization',v_org::text,NULL,NULL,NULL,NULL,NULL,
    'Propriedade transferida',jsonb_build_object('previous_owner_member_id',v_current_owner,'new_owner_member_id',p_target_member_id),NULL);
END;
$$;

-- Auditoria multi-organização: mantém a assinatura para não quebrar os serviços existentes.
CREATE OR REPLACE FUNCTION public.append_audit_event(
  p_source text,
  p_action text,
  p_entity_type text,
  p_entity_id text DEFAULT NULL,
  p_lead_id bigint DEFAULT NULL,
  p_queue_item_id bigint DEFAULT NULL,
  p_channel_id bigint DEFAULT NULL,
  p_previous_status_id bigint DEFAULT NULL,
  p_target_status_id bigint DEFAULT NULL,
  p_message text DEFAULT NULL,
  p_metadata jsonb DEFAULT '{}'::jsonb,
  p_users_id bigint DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_scope_users_id bigint;
  v_org bigint;
  v_actor_users_id bigint;
  v_actor_member_id bigint;
  v_actor_type text;
  v_actor_name text;
  v_id bigint;
BEGIN
  IF auth.role()='service_role' THEN
    v_scope_users_id:=p_users_id;
    SELECT o.organizations_id INTO v_org FROM public.organizations o WHERE o.legacy_scope_users_id=v_scope_users_id LIMIT 1;
    v_actor_type:='system';
  ELSE
    v_scope_users_id:=public.ensure_current_user();
    v_org:=public.current_organization_id();
    v_actor_users_id:=public.current_actor_user_id();
    v_actor_member_id:=public.current_organization_member_id();
    v_actor_type:=CASE WHEN public.is_platform_owner(v_actor_users_id) AND v_actor_member_id IS NULL THEN 'platform_owner' ELSE 'member' END;
    SELECT u.users_name INTO v_actor_name FROM public.users u WHERE u.users_id=v_actor_users_id;
    IF p_users_id IS NOT NULL AND p_users_id<>v_scope_users_id THEN RAISE EXCEPTION 'audit_forbidden'; END IF;
  END IF;
  IF v_scope_users_id IS NULL THEN RAISE EXCEPTION 'audit_user_required'; END IF;
  IF nullif(trim(coalesce(p_source,'')),'') IS NULL OR nullif(trim(coalesce(p_action,'')),'') IS NULL THEN RAISE EXCEPTION 'audit_source_action_required'; END IF;

  INSERT INTO public.audit_events(
    users_id,organizations_id,actor_auth_user_id,actor_users_id,actor_member_id,actor_type,
    source,action,entity_type,entity_id,lead_id,queue_item_id,channel_id,previous_status_id,target_status_id,message,metadata
  ) VALUES (
    v_scope_users_id,v_org,auth.uid(),v_actor_users_id,v_actor_member_id,v_actor_type,
    trim(p_source),trim(p_action),coalesce(nullif(trim(p_entity_type),''),'system'),p_entity_id,
    p_lead_id,p_queue_item_id,p_channel_id,p_previous_status_id,p_target_status_id,p_message,
    coalesce(p_metadata,'{}'::jsonb) || jsonb_build_object('actor_name',v_actor_name,'actor_type',v_actor_type,'actor_member_id',v_actor_member_id)
  ) RETURNING audit_events_id INTO v_id;
  RETURN v_id;
END;
$$;

