        organizations_name, organizations_slug, legacy_scope_users_id, status_id, created_by_users_id
      ) VALUES (v_name, v_slug, r.users_id, 1, r.users_id)
      RETURNING organizations_id INTO v_org_id;
    END IF;

    INSERT INTO public.organization_roles(
      organizations_id, organization_roles_name, organization_roles_key,
      organization_roles_description, is_system_template, is_editable, status_id, created_by_users_id
