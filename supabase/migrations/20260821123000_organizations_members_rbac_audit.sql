CREATE OR REPLACE FUNCTION public.has_organization_permission(p_permission_key text)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
STABLE
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_member public.organization_members%ROWTYPE;
BEGIN
  IF public.is_platform_owner() THEN RETURN true; END IF;

  SELECT * INTO v_member
    FROM public.organization_members m
   WHERE m.organization_members_id=public.current_organization_member_id()
     AND m.status_id=1;

  IF v_member.organization_members_id IS NULL THEN RETURN false; END IF;
  IF v_member.access_level='owner' THEN
    RETURN EXISTS(
      SELECT 1 FROM public.permissions p
       WHERE p.permissions_key=p_permission_key
         AND p.permissions_sensitivity<>'platform_only'
    );
  END IF;

  -- Gestor sempre mantém o mínimo gerencial definido pela plataforma.
  IF v_member.access_level='manager' AND p_permission_key = ANY(ARRAY[
    'organization.view','members.view','members.invite','members.edit','members.deactivate','roles.view','audit.view'
  ]) THEN
    RETURN true;
  END IF;

  RETURN EXISTS(
    SELECT 1
      FROM public.organization_role_permissions rp
      JOIN public.permissions p ON p.permissions_id=rp.permissions_id
     WHERE rp.organization_roles_id=v_member.organization_roles_id
       AND p.permissions_key=p_permission_key
       AND p.permissions_sensitivity='delegable'
  );
END;
$$;

-- Gestores podem alocar funções em Membros, mas nunca escalar privilégios acima
-- das próprias permissões efetivas. Dono/Platform Owner podem alocar qualquer
-- função delegável da organização.
CREATE OR REPLACE FUNCTION public.can_assign_organization_role(p_role_id bigint)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
STABLE
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_level text:=public.current_access_level();
  v_org bigint:=public.current_organization_id();
BEGIN
  IF p_role_id IS NULL THEN RETURN false; END IF;
  IF NOT EXISTS(
    SELECT 1 FROM public.organization_roles r
     WHERE r.organization_roles_id=p_role_id
       AND r.organizations_id=v_org
       AND r.status_id=1
  ) THEN RETURN false; END IF;

  IF v_level IN ('platform_owner','owner') THEN RETURN true; END IF;
  IF v_level<>'manager' THEN RETURN false; END IF;

  RETURN NOT EXISTS(
    SELECT 1
      FROM public.organization_role_permissions rp
      JOIN public.permissions p ON p.permissions_id=rp.permissions_id
     WHERE rp.organization_roles_id=p_role_id
       AND NOT public.has_organization_permission(p.permissions_key)
  );
END;
$$;

-- Mantém o contrato histórico dos serviços existentes, mas agora users_id é o escopo
-- técnico da organização ativa. A conta humana é obtida por current_actor_user_id().
CREATE OR REPLACE FUNCTION public.ensure_current_user()
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_auth uuid:=auth.uid();
  v_actor bigint;
  v_scope bigint;
BEGIN
  IF v_auth IS NULL THEN RAISE EXCEPTION 'authentication_required'; END IF;

  SELECT u.users_id INTO v_actor
    FROM public.users u
   WHERE u.auth_user_id=v_auth AND coalesce(u.users_is_scope,false)=false;

  IF v_actor IS NULL THEN
    INSERT INTO public.users(auth_user_id,status_id,users_is_scope)
    VALUES(v_auth,1,false)
    ON CONFLICT(auth_user_id) DO UPDATE SET auth_user_id=excluded.auth_user_id
    RETURNING users_id INTO v_actor;
  END IF;

  v_scope := public.current_organization_scope_users_id();
  RETURN coalesce(v_scope,v_actor);
END;
$$;

-- Preenche organização e autoria em novas gravações feitas pelo CRM autenticado.
CREATE OR REPLACE FUNCTION public.apply_organization_scope()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_org bigint:=public.current_organization_id();
  v_scope bigint:=public.current_organization_scope_users_id();
BEGIN
  IF auth.role() <> 'service_role' AND v_org IS NOT NULL THEN
    NEW.organizations_id := v_org;
    IF v_scope IS NOT NULL THEN NEW.users_id := v_scope; END IF;
  ELSIF NEW.organizations_id IS NULL AND NEW.users_id IS NOT NULL THEN
    SELECT o.organizations_id INTO NEW.organizations_id
      FROM public.organizations o
     WHERE o.legacy_scope_users_id=NEW.users_id
     LIMIT 1;
  END IF;
  RETURN NEW;
END;
$$;

DO $scope_triggers$
DECLARE
  r record;
  v_trigger text;
BEGIN
  FOR r IN
    SELECT c.table_name
      FROM information_schema.columns c
     WHERE c.table_schema='public'
       AND c.column_name='users_id'
       AND EXISTS(
         SELECT 1 FROM information_schema.columns c2
          WHERE c2.table_schema='public' AND c2.table_name=c.table_name AND c2.column_name='organizations_id'
       )
       AND c.table_name NOT IN ('organization_members','user_active_organizations')
  LOOP
    v_trigger := 'apply_organization_scope_' || r.table_name;
    EXECUTE format('DROP TRIGGER IF EXISTS %I ON public.%I',v_trigger,r.table_name);
    EXECUTE format('CREATE TRIGGER %I BEFORE INSERT OR UPDATE OF users_id,organizations_id ON public.%I FOR EACH ROW EXECUTE FUNCTION public.apply_organization_scope()',v_trigger,r.table_name);
  END LOOP;
END
$scope_triggers$;

