-- Edge Functions usam service_role para acessar tabelas, mas a autorização continua
-- sendo a do usuário autenticado que originou a chamada.
CREATE OR REPLACE FUNCTION public.auth_user_has_organization_permission(
  p_auth_user_id uuid,
  p_organization_id bigint,
  p_permission_key text
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
STABLE
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_actor bigint;
  v_member public.organization_members%ROWTYPE;
BEGIN
  IF auth.role()<>'service_role' THEN RAISE EXCEPTION 'service_role_required'; END IF;
  IF p_auth_user_id IS NULL OR p_organization_id IS NULL OR nullif(trim(coalesce(p_permission_key,'')),'') IS NULL THEN RETURN false; END IF;

  SELECT u.users_id INTO v_actor
    FROM public.users u
   WHERE u.auth_user_id=p_auth_user_id AND coalesce(u.users_is_scope,false)=false
   LIMIT 1;
  IF v_actor IS NULL THEN RETURN false; END IF;
  IF public.is_platform_owner(v_actor) THEN RETURN true; END IF;

  SELECT * INTO v_member
    FROM public.organization_members m
   WHERE m.organizations_id=p_organization_id
     AND m.users_id=v_actor
     AND m.status_id=1
   LIMIT 1;
  IF v_member.organization_members_id IS NULL THEN RETURN false; END IF;

  IF v_member.access_level='owner' THEN
    RETURN EXISTS(
      SELECT 1 FROM public.permissions p
       WHERE p.permissions_key=p_permission_key
         AND p.permissions_sensitivity<>'platform_only'
    );
  END IF;

  IF v_member.access_level='manager' AND p_permission_key = ANY(ARRAY[
    'organization.view','members.view','members.invite','members.edit','members.deactivate','roles.view','audit.view'
  ]) THEN RETURN true; END IF;

  RETURN EXISTS(
    SELECT 1
      FROM public.organization_role_permissions rp
      JOIN public.permissions p ON p.permissions_id=rp.permissions_id
     WHERE rp.organization_roles_id=v_member.organization_roles_id
       AND p.permissions_key=p_permission_key
       AND p.permissions_sensitivity='delegable'
  );
END;
$$;

