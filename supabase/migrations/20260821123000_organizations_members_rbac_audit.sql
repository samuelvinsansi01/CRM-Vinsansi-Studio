CREATE OR REPLACE FUNCTION public.create_organization_invitation(
  p_email text,
  p_access_level text,
  p_role_id bigint
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public, auth
AS $$
DECLARE
  v_org bigint:=public.current_organization_id();
  v_actor_member bigint:=public.current_organization_member_id();
  v_email text:=lower(trim(coalesce(p_email,'')));
  v_level text:=lower(trim(coalesce(p_access_level,'member')));
  v_role bigint:=p_role_id;
  v_id uuid;
  v_token uuid;
BEGIN
  IF NOT (public.current_access_level() IN ('owner','manager','platform_owner') OR public.has_organization_permission('members.invite')) THEN
    RAISE EXCEPTION 'permission_denied:members.invite';
  END IF;
  IF v_email='' OR position('@' in v_email)<2 THEN RAISE EXCEPTION 'invalid_email'; END IF;
  IF EXISTS(
    SELECT 1
      FROM public.organization_members m
      JOIN public.users u ON u.users_id=m.users_id
      JOIN auth.users au ON au.id=u.auth_user_id
     WHERE m.organizations_id=v_org AND m.status_id=1 AND lower(au.email)=v_email
  ) THEN RAISE EXCEPTION 'member_already_active'; END IF;
  IF v_level NOT IN ('manager','member') THEN RAISE EXCEPTION 'invalid_access_level'; END IF;
  IF public.current_access_level()='manager' AND v_level<>'member' THEN RAISE EXCEPTION 'manager_cannot_promote_manager'; END IF;

  IF v_role IS NULL THEN
    SELECT organization_roles_id INTO v_role FROM public.organization_roles
     WHERE organizations_id=v_org AND organization_roles_key=CASE WHEN v_level='manager' THEN 'gestor' ELSE 'sdr' END;
  END IF;
  IF v_role IS NOT NULL AND NOT EXISTS(SELECT 1 FROM public.organization_roles WHERE organization_roles_id=v_role AND organizations_id=v_org AND status_id=1) THEN
    RAISE EXCEPTION 'role_not_available';
  END IF;
  IF public.current_access_level()='manager' AND NOT public.can_assign_organization_role(v_role) THEN
    RAISE EXCEPTION 'manager_cannot_assign_role_with_higher_permissions';
  END IF;

  UPDATE public.organization_invitations SET invitation_status='expired',organization_invitations_updated_at=now()
   WHERE organizations_id=v_org AND lower(invite_email)=v_email AND invitation_status='pending' AND expires_at<=now();

  INSERT INTO public.organization_invitations(organizations_id,invite_email,access_level,organization_roles_id,invited_by_member_id)
  VALUES(v_org,v_email,v_level,v_role,v_actor_member)
  ON CONFLICT (organizations_id, (lower(invite_email))) WHERE invitation_status='pending'
  DO UPDATE SET access_level=excluded.access_level,organization_roles_id=excluded.organization_roles_id,
                invited_by_member_id=excluded.invited_by_member_id,expires_at=now()+interval '7 days',
                invitation_token=gen_random_uuid(),organization_invitations_updated_at=now()
  RETURNING organization_invitations_id,invitation_token INTO v_id,v_token;

  PERFORM public.append_audit_event('organization','member_invited','organization_invitation',v_id::text,NULL,NULL,NULL,NULL,NULL,
    'Convite criado',jsonb_build_object('email',v_email,'access_level',v_level),NULL);
  RETURN jsonb_build_object('invitationId',v_id::text,'token',v_token::text,'email',v_email,'accessLevel',v_level,'organizationId',v_org::text);
END;
$$;

CREATE OR REPLACE FUNCTION public.accept_current_user_invitations()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public, auth
AS $$
DECLARE
  v_actor bigint:=public.current_actor_user_id();
  v_email text;
  r record;
  v_count integer:=0;
BEGIN
  IF v_actor IS NULL THEN RETURN 0; END IF;
  SELECT lower(au.email) INTO v_email FROM auth.users au JOIN public.users u ON u.auth_user_id=au.id WHERE u.users_id=v_actor;
  IF v_email IS NULL THEN RETURN 0; END IF;

  UPDATE public.organization_invitations SET invitation_status='expired',organization_invitations_updated_at=now()
   WHERE invitation_status='pending' AND expires_at<=now();

  FOR r IN
    SELECT * FROM public.organization_invitations i
     WHERE lower(i.invite_email)=v_email AND i.invitation_status='pending' AND i.expires_at>now()
     ORDER BY i.organization_invitations_created_at
  LOOP
    INSERT INTO public.organization_members(organizations_id,users_id,access_level,organization_roles_id,status_id,invited_by_member_id)
    VALUES(r.organizations_id,v_actor,r.access_level,r.organization_roles_id,1,r.invited_by_member_id)
    ON CONFLICT(organizations_id,users_id) DO UPDATE SET
      access_level=excluded.access_level,organization_roles_id=excluded.organization_roles_id,status_id=1,
      deactivated_at=NULL,deactivated_by_member_id=NULL,organization_members_updated_at=now();

    UPDATE public.organization_invitations
       SET invitation_status='accepted',accepted_by_users_id=v_actor,accepted_at=now(),organization_invitations_updated_at=now()
     WHERE organization_invitations_id=r.organization_invitations_id;
    v_count:=v_count+1;
  END LOOP;

  IF v_count>0 AND NOT EXISTS(SELECT 1 FROM public.user_active_organizations WHERE users_id=v_actor) THEN
    INSERT INTO public.user_active_organizations(users_id,organizations_id)
    SELECT v_actor,m.organizations_id FROM public.organization_members m WHERE m.users_id=v_actor AND m.status_id=1 ORDER BY m.organizations_id LIMIT 1;
  END IF;
  RETURN v_count;
END;
$$;

