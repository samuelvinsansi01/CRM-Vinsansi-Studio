-- Todas as tabelas já existentes que usam users_id passam a ter também a organização
-- canônica. users_id continua temporariamente como chave de escopo de compatibilidade,
-- mas deixa de representar propriedade humana do recurso.
DO $tenant_columns$
DECLARE
  r record;
BEGIN
  FOR r IN
    SELECT c.table_name
      FROM information_schema.columns c
     WHERE c.table_schema='public'
       AND c.column_name='users_id'
       AND c.table_name NOT IN (
         'users','platform_owners','organization_members','user_active_organizations'
       )
  LOOP
    EXECUTE format('ALTER TABLE public.%I ADD COLUMN IF NOT EXISTS organizations_id bigint', r.table_name);
    EXECUTE format(
      'UPDATE public.%I t SET organizations_id=o.organizations_id FROM public.organizations o WHERE t.organizations_id IS NULL AND o.legacy_scope_users_id=t.users_id',
      r.table_name
    );
    EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON public.%I(organizations_id)', r.table_name || '_organization_idx', r.table_name);
  END LOOP;
END
$tenant_columns$;

-- organizations_id é a propriedade canônica. Depois do backfill, nenhum registro
-- comercial/operacional pode permanecer sem tenant e todas as referências ficam
-- protegidas por FK no próprio banco.
DO $tenant_integrity$
DECLARE
  r record;
  v_constraint text;
  v_nulls bigint;
BEGIN
  FOR r IN
    SELECT c.table_name
      FROM information_schema.columns c
     WHERE c.table_schema='public'
       AND c.column_name='users_id'
       AND c.table_name NOT IN (
         'users','platform_owners','organization_members','user_active_organizations'
       )
       AND EXISTS(
         SELECT 1 FROM information_schema.columns c2
          WHERE c2.table_schema='public' AND c2.table_name=c.table_name AND c2.column_name='organizations_id'
       )
  LOOP
    EXECUTE format('SELECT count(*) FROM public.%I WHERE organizations_id IS NULL',r.table_name) INTO v_nulls;
    IF v_nulls > 0 THEN
      RAISE EXCEPTION 'organization_backfill_incomplete:%:%',r.table_name,v_nulls;
    END IF;
    EXECUTE format('ALTER TABLE public.%I ALTER COLUMN organizations_id SET NOT NULL',r.table_name);
    v_constraint := left(r.table_name || '_organizations_id_fkey',63);
    IF NOT EXISTS(
      SELECT 1 FROM pg_constraint pc
       WHERE pc.conrelid=format('public.%I',r.table_name)::regclass
         AND pc.conname=v_constraint
    ) THEN
      EXECUTE format(
        'ALTER TABLE public.%I ADD CONSTRAINT %I FOREIGN KEY (organizations_id) REFERENCES public.organizations(organizations_id) ON DELETE RESTRICT NOT VALID',
        r.table_name,v_constraint
      );
      EXECUTE format('ALTER TABLE public.%I VALIDATE CONSTRAINT %I',r.table_name,v_constraint);
    END IF;
  END LOOP;
END
$tenant_integrity$;

-- Garante que a função atribuída a um membro/convite pertence à mesma organização.
CREATE OR REPLACE FUNCTION public.validate_organization_role_scope()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO pg_catalog, public
AS $$
DECLARE v_role_org bigint;
BEGIN
  IF NEW.organization_roles_id IS NULL THEN RETURN NEW; END IF;
  SELECT r.organizations_id INTO v_role_org
    FROM public.organization_roles r
   WHERE r.organization_roles_id=NEW.organization_roles_id;
  IF v_role_org IS NULL OR v_role_org<>NEW.organizations_id THEN
    RAISE EXCEPTION 'organization_role_scope_mismatch';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS validate_organization_member_role_scope ON public.organization_members;
CREATE TRIGGER validate_organization_member_role_scope
BEFORE INSERT OR UPDATE OF organizations_id,organization_roles_id ON public.organization_members
FOR EACH ROW EXECUTE FUNCTION public.validate_organization_role_scope();
DROP TRIGGER IF EXISTS validate_organization_invitation_role_scope ON public.organization_invitations;
CREATE TRIGGER validate_organization_invitation_role_scope
BEFORE INSERT OR UPDATE OF organizations_id,organization_roles_id ON public.organization_invitations
FOR EACH ROW EXECUTE FUNCTION public.validate_organization_role_scope();

