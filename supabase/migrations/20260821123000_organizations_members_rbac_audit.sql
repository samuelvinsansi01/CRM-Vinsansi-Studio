-- Nenhuma FK de autoria/responsabilidade pode apontar para membro de outro tenant.
CREATE OR REPLACE FUNCTION public.validate_member_attribution_scope()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_doc jsonb:=to_jsonb(NEW);
  v_org bigint;
  v_column text;
  v_member_id bigint;
BEGIN
  v_org:=nullif(v_doc->>'organizations_id','')::bigint;
  IF v_org IS NULL THEN RETURN NEW; END IF;
  FOREACH v_column IN ARRAY TG_ARGV LOOP
    v_member_id:=nullif(v_doc->>v_column,'')::bigint;
    IF v_member_id IS NOT NULL AND NOT EXISTS(
      SELECT 1 FROM public.organization_members m
       WHERE m.organization_members_id=v_member_id
         AND m.organizations_id=v_org
    ) THEN
      RAISE EXCEPTION 'member_attribution_scope_mismatch:%',v_column;
    END IF;
  END LOOP;
  RETURN NEW;
END;
$$;

