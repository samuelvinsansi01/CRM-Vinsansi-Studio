      v_name := CASE WHEN v_count = 1 THEN 'Vinsansi Studio'
                     ELSE coalesce(nullif(trim(r.users_name),''), 'Organização ' || r.users_id::text) END;
      v_slug := lower(regexp_replace(v_name, '[^a-zA-Z0-9]+', '-', 'g'));
