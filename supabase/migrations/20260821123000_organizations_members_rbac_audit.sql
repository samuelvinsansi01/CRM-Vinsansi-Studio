CREATE OR REPLACE FUNCTION public.current_organization_id()
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
STABLE
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_actor bigint := public.current_actor_user_id();
  v_org bigint;
  v_header text;
  v_headers jsonb;
BEGIN
  IF v_actor IS NULL THEN RETURN NULL; END IF;

  -- Contexto preferencial por sessão/cliente. O CRM injeta este header em todas
  -- as consultas Supabase; assim duas sessões do mesmo usuário podem operar
  -- organizações diferentes sem disputar um único estado global.
  BEGIN
    v_headers := nullif(current_setting('request.headers', true),'')::jsonb;
    v_header := nullif(trim(coalesce(v_headers->>'x-vinsansi-organization-id','')),'');
    IF v_header ~ '^[0-9]+$' THEN
      v_org := v_header::bigint;
      IF public.can_access_organization(v_org) THEN RETURN v_org; END IF;
      v_org := NULL;
    END IF;
  EXCEPTION WHEN others THEN
    v_org := NULL;
  END;

  -- Fallback persistente para clientes ainda não migrados ao header organizacional.
  SELECT a.organizations_id INTO v_org
    FROM public.user_active_organizations a
   WHERE a.users_id=v_actor
     AND public.can_access_organization(a.organizations_id)
   LIMIT 1;

  IF v_org IS NOT NULL THEN RETURN v_org; END IF;

  SELECT m.organizations_id INTO v_org
    FROM public.organization_members m
   WHERE m.users_id=v_actor AND m.status_id=1
   ORDER BY CASE m.access_level WHEN 'owner' THEN 1 WHEN 'manager' THEN 2 ELSE 3 END,
            m.organizations_id
   LIMIT 1;

  IF v_org IS NULL AND public.is_platform_owner(v_actor) THEN
    SELECT o.organizations_id INTO v_org
      FROM public.organizations o
     WHERE o.status_id=1
     ORDER BY o.organizations_id
     LIMIT 1;
  END IF;

  RETURN v_org;
END;
$$;

