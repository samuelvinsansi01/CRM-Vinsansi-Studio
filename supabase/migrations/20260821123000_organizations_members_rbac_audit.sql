CREATE OR REPLACE FUNCTION public.save_organization_role(
  p_role_id bigint,
  p_name text,
  p_description text,
  p_permission_keys text[]
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_org bigint:=public.current_organization_id();
  v_actor bigint:=public.current_actor_user_id();
  v_id bigint:=p_role_id;
  v_key text;
BEGIN
  IF NOT (public.is_platform_owner() OR public.current_access_level()='owner') THEN
    RAISE EXCEPTION 'permission_denied:roles.manage';
  END IF;
  IF trim(coalesce(p_name,''))='' THEN RAISE EXCEPTION 'role_name_required'; END IF;

  IF v_id IS NULL THEN
    v_key:=trim(both '-' from lower(regexp_replace(p_name,'[^a-zA-Z0-9]+','-','g')))||'-'||substr(gen_random_uuid()::text,1,8);
    INSERT INTO public.organization_roles(organizations_id,organization_roles_name,organization_roles_key,organization_roles_description,is_system_template,is_editable,status_id,created_by_users_id)
    VALUES(v_org,trim(p_name),v_key,nullif(trim(coalesce(p_description,'')),''),false,true,1,v_actor)
    RETURNING organization_roles_id INTO v_id;
  ELSE
    IF NOT EXISTS(SELECT 1 FROM public.organization_roles WHERE organization_roles_id=v_id AND organizations_id=v_org) THEN
      RAISE EXCEPTION 'role_not_found';
    END IF;
    UPDATE public.organization_roles
       SET organization_roles_name=trim(p_name),organization_roles_description=nullif(trim(coalesce(p_description,'')),''),organization_roles_updated_at=now()
     WHERE organization_roles_id=v_id;
  END IF;

  DELETE FROM public.organization_role_permissions WHERE organization_roles_id=v_id;
  INSERT INTO public.organization_role_permissions(organization_roles_id,permissions_id,granted_by_users_id)
  SELECT v_id,p.permissions_id,v_actor
    FROM public.permissions p
   WHERE p.permissions_sensitivity='delegable'
     AND p.permissions_key=ANY(coalesce(p_permission_keys,ARRAY[]::text[]));

  PERFORM public.append_audit_event('organization','role_saved','organization_role',v_id::text,NULL,NULL,NULL,NULL,NULL,
    'Função salva',jsonb_build_object('name',trim(p_name),'permission_keys',coalesce(p_permission_keys,ARRAY[]::text[])),NULL);
  RETURN v_id;
END;
$$;

