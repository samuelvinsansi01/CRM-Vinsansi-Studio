DECLARE
  r record;
  v_org_id bigint;
  v_name text;
  v_slug text;
  v_role_manager bigint;
  v_role_sdr bigint;
  v_count integer := 0;
BEGIN
  FOR r IN
    SELECT u.users_id, u.users_name
      FROM public.users u
     WHERE coalesce(u.users_is_scope,false) = false
     ORDER BY u.users_id
  LOOP
    v_count := v_count + 1;
    SELECT o.organizations_id INTO v_org_id
      FROM public.organizations o
     WHERE o.legacy_scope_users_id = r.users_id;

