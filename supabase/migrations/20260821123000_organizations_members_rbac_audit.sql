CREATE OR REPLACE FUNCTION public.get_organization_context()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
STABLE
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_actor bigint:=public.current_actor_user_id();
  v_org bigint:=public.current_organization_id();
  v_member public.organization_members%ROWTYPE;
  v_org_row public.organizations%ROWTYPE;
  v_member_name text;
  v_role_name text;
  v_permissions jsonb;
  v_orgs jsonb;
BEGIN
  IF v_actor IS NULL THEN RAISE EXCEPTION 'authentication_required'; END IF;
  IF v_org IS NULL THEN
    RETURN jsonb_build_object('actorUsersId',v_actor,'organization',NULL,'organizations','[]'::jsonb,'permissions','[]'::jsonb,'isPlatformOwner',public.is_platform_owner(v_actor));
  END IF;

  SELECT * INTO v_org_row FROM public.organizations WHERE organizations_id=v_org;
  SELECT * INTO v_member FROM public.organization_members
   WHERE organizations_id=v_org AND users_id=v_actor AND status_id=1 LIMIT 1;
  SELECT coalesce(nullif(trim(users_name),''),'Usuário') INTO v_member_name FROM public.users WHERE users_id=v_actor;
  IF v_member.organization_roles_id IS NOT NULL THEN
    SELECT organization_roles_name INTO v_role_name FROM public.organization_roles WHERE organization_roles_id=v_member.organization_roles_id;
  END IF;

  SELECT coalesce(jsonb_agg(p.permissions_key ORDER BY p.permissions_key),'[]'::jsonb)
    INTO v_permissions
    FROM public.permissions p
   WHERE public.has_organization_permission(p.permissions_key);

  SELECT coalesce(jsonb_agg(jsonb_build_object(
      'id',x.organizations_id::text,'name',x.organizations_name,'accessLevel',x.access_level,
      'memberId',CASE WHEN x.organization_members_id IS NULL THEN NULL ELSE x.organization_members_id::text END,
      'roleName',x.role_name,'active',x.is_active_context
    ) ORDER BY x.organizations_name),'[]'::jsonb)
    INTO v_orgs
    FROM public.list_my_organizations() x;

  RETURN jsonb_build_object(
    'actorUsersId',v_actor::text,
    'isPlatformOwner',public.is_platform_owner(v_actor),
    'organization',jsonb_build_object(
      'id',v_org_row.organizations_id::text,
      'name',v_org_row.organizations_name,
      'slug',v_org_row.organizations_slug,
      'legacyScopeUsersId',v_org_row.legacy_scope_users_id::text
    ),
    'member',CASE WHEN v_member.organization_members_id IS NULL THEN NULL ELSE jsonb_build_object(
      'id',v_member.organization_members_id::text,
      'name',v_member_name,
      'accessLevel',v_member.access_level,
      'roleId',CASE WHEN v_member.organization_roles_id IS NULL THEN NULL ELSE v_member.organization_roles_id::text END,
      'roleName',v_role_name
    ) END,
    'permissions',v_permissions,
    'organizations',v_orgs
  );
END;
$$;

-- Criação de organização: Platform Owner pode criar qualquer organização; um usuário
-- comum só cria quando ainda não possui organização ativa.
-- Resolve contexto organizacional para APIs/Edge Functions que validam um auth.users.id
-- usando service_role. O retorno nunca depende de um users_id fornecido pelo cliente.
CREATE OR REPLACE FUNCTION public.resolve_organization_context_for_auth_user(
  p_auth_user_id uuid,
  p_organization_id bigint DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
STABLE
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_actor bigint;
  v_org bigint;
  v_scope bigint;
  v_member bigint;
  v_level text;
  v_platform boolean;
BEGIN
  SELECT u.users_id INTO v_actor
    FROM public.users u
   WHERE u.auth_user_id=p_auth_user_id
     AND coalesce(u.users_is_scope,false)=false
   LIMIT 1;
  IF v_actor IS NULL THEN RAISE EXCEPTION 'public_user_not_found'; END IF;
  v_platform := public.is_platform_owner(v_actor);

  -- APIs/Edge Functions podem informar o tenant selecionado pelo cliente.
  -- A função valida a associação do usuário antes de aceitar esse contexto.
  IF p_organization_id IS NOT NULL THEN
    IF EXISTS(SELECT 1 FROM public.organizations o WHERE o.organizations_id=p_organization_id AND o.status_id=1)
       AND (v_platform OR EXISTS(
         SELECT 1 FROM public.organization_members m
          WHERE m.organizations_id=p_organization_id AND m.users_id=v_actor AND m.status_id=1
       )) THEN
      v_org := p_organization_id;
    ELSE
      RAISE EXCEPTION 'organization_access_denied';
    END IF;
  END IF;

  IF v_org IS NULL THEN
    SELECT a.organizations_id INTO v_org
      FROM public.user_active_organizations a
      JOIN public.organizations o ON o.organizations_id=a.organizations_id AND o.status_id=1
     WHERE a.users_id=v_actor
       AND (v_platform OR EXISTS(
         SELECT 1 FROM public.organization_members m
          WHERE m.organizations_id=a.organizations_id AND m.users_id=v_actor AND m.status_id=1
       ))
     LIMIT 1;
  END IF;

  IF v_org IS NULL THEN
    SELECT m.organizations_id INTO v_org
      FROM public.organization_members m
      JOIN public.organizations o ON o.organizations_id=m.organizations_id AND o.status_id=1
     WHERE m.users_id=v_actor AND m.status_id=1
     ORDER BY CASE m.access_level WHEN 'owner' THEN 1 WHEN 'manager' THEN 2 ELSE 3 END,m.organizations_id
     LIMIT 1;
  END IF;

  IF v_org IS NULL AND v_platform THEN
    SELECT o.organizations_id INTO v_org FROM public.organizations o WHERE o.status_id=1 ORDER BY o.organizations_id LIMIT 1;
  END IF;
  IF v_org IS NULL THEN RAISE EXCEPTION 'organization_context_not_found'; END IF;

  SELECT o.legacy_scope_users_id INTO v_scope FROM public.organizations o WHERE o.organizations_id=v_org;
  SELECT m.organization_members_id,m.access_level INTO v_member,v_level
    FROM public.organization_members m
   WHERE m.organizations_id=v_org AND m.users_id=v_actor AND m.status_id=1 LIMIT 1;

  RETURN jsonb_build_object(
    'actorUsersId',v_actor::text,
    'organizationId',v_org::text,
    'scopeUsersId',v_scope::text,
    'memberId',CASE WHEN v_member IS NULL THEN NULL ELSE v_member::text END,
    'accessLevel',CASE WHEN v_platform AND v_member IS NULL THEN 'platform_owner' ELSE coalesce(v_level,'platform_owner') END,
    'isPlatformOwner',v_platform
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.create_organization(p_name text)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_actor bigint:=public.current_actor_user_id();
  v_scope bigint;
  v_org bigint;
  v_name text:=trim(coalesce(p_name,''));
  v_slug text;
BEGIN
  IF v_actor IS NULL THEN RAISE EXCEPTION 'authentication_required'; END IF;
  IF v_name='' THEN RAISE EXCEPTION 'organization_name_required'; END IF;
  IF NOT public.is_platform_owner(v_actor) AND EXISTS(SELECT 1 FROM public.organization_members WHERE users_id=v_actor AND status_id=1) THEN
    RAISE EXCEPTION 'organization_creation_forbidden';
  END IF;

  INSERT INTO public.users(auth_user_id,status_id,users_name,users_is_scope)
  VALUES(gen_random_uuid(),1,'[escopo] '||v_name,true)
  RETURNING users_id INTO v_scope;

  v_slug:=trim(both '-' from lower(regexp_replace(v_name,'[^a-zA-Z0-9]+','-','g')));
  IF v_slug='' THEN v_slug:='organizacao'; END IF;
  v_slug:=v_slug||'-'||v_scope::text;

  INSERT INTO public.organizations(organizations_name,organizations_slug,legacy_scope_users_id,status_id,created_by_users_id)
  VALUES(v_name,v_slug,v_scope,1,v_actor)
  RETURNING organizations_id INTO v_org;

  INSERT INTO public.organization_roles(organizations_id,organization_roles_name,organization_roles_key,organization_roles_description,is_system_template,is_editable,status_id,created_by_users_id)
  VALUES
    (v_org,'Gestor','gestor','Preset gerencial. O nível Gestor mantém poderes mínimos obrigatórios.',true,true,1,v_actor),
    (v_org,'SDR','sdr','Preset comercial para prospecção, captura, validação, disparo e resposta.',true,true,1,v_actor);

  INSERT INTO public.organization_role_permissions(organization_roles_id,permissions_id,granted_by_users_id)
  SELECT r.organization_roles_id,p.permissions_id,v_actor
    FROM public.organization_roles r
