CREATE UNIQUE INDEX IF NOT EXISTS chips_one_active_per_instance_unique
  ON public.chips(users_id, instances_id)
  WHERE status_id = 1;

CREATE TABLE IF NOT EXISTS public.conversations (
  conversations_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  users_id bigint NOT NULL REFERENCES public.users(users_id) ON DELETE CASCADE,
  chips_id bigint NOT NULL REFERENCES public.chips(chips_id) ON DELETE CASCADE,
  instances_id bigint NOT NULL REFERENCES public.instances(instances_id) ON DELETE CASCADE,
  leads_id bigint REFERENCES public.leads(leads_id) ON DELETE SET NULL,
  remote_jid text NOT NULL,
  contact_phone text,
  contact_name text,
  contact_avatar_url text,
  conversation_status text NOT NULL DEFAULT 'open' CHECK (conversation_status IN ('open','archived')),
  unread_count integer NOT NULL DEFAULT 0 CHECK (unread_count >= 0),
  last_message_at timestamptz,
  last_message_preview text,
  last_message_direction text CHECK (last_message_direction IS NULL OR last_message_direction IN ('inbound','outbound')),
  last_read_at timestamptz,
  conversations_created_at timestamptz NOT NULL DEFAULT now(),
  conversations_updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(users_id, chips_id, remote_jid)
);

CREATE TABLE IF NOT EXISTS public.conversation_messages (
  conversation_messages_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  users_id bigint NOT NULL REFERENCES public.users(users_id) ON DELETE CASCADE,
  conversations_id bigint NOT NULL REFERENCES public.conversations(conversations_id) ON DELETE CASCADE,
  chips_id bigint NOT NULL REFERENCES public.chips(chips_id) ON DELETE CASCADE,
  instances_id bigint NOT NULL REFERENCES public.instances(instances_id) ON DELETE CASCADE,
  leads_id bigint REFERENCES public.leads(leads_id) ON DELETE SET NULL,
  external_message_id text,
  client_idempotency_key uuid,
  remote_jid text NOT NULL,
  direction text NOT NULL CHECK (direction IN ('inbound','outbound')),
  from_me boolean NOT NULL DEFAULT false,
  message_type text NOT NULL DEFAULT 'text',
  message_body text,
  media_url text,
  media_mime_type text,
  media_file_name text,
  quoted_external_message_id text,
  message_status text NOT NULL DEFAULT 'pending'
    CHECK (message_status IN ('pending','sending','sent','delivered','read','failed','deleted','reconciliation_required')),
  provider_timestamp timestamptz,
  raw_payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  error_message text,
  conversation_messages_created_at timestamptz NOT NULL DEFAULT now(),
  conversation_messages_updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS conversation_messages_external_unique
  ON public.conversation_messages(instances_id, external_message_id)
