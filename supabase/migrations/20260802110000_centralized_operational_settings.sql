CREATE OR REPLACE FUNCTION public.service_get_operational_settings(p_users_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_row public.user_operational_settings%ROWTYPE;
BEGIN
  IF auth.role() <> 'service_role' THEN RAISE EXCEPTION 'service_role_required'; END IF;
  v_row := public.ensure_user_operational_settings(p_users_id);
  RETURN jsonb_build_object(
    'users_id', v_row.users_id,
    'dispatch', v_row.dispatch_settings,
    'import', v_row.import_settings,
    'extension', v_row.extension_runtime_config,
    'timezone', v_row.operational_timezone,
    'cutoffHour', v_row.operational_cutoff_hour,
    'version', v_row.settings_version,
    'updatedAt', v_row.user_operational_settings_updated_at
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.worker_defer_batch(
  p_worker_batches_id bigint,
  p_next_run_at timestamptz,
  p_reason text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public
AS $$
BEGIN
  IF auth.role() <> 'service_role' THEN RAISE EXCEPTION 'service_role_required'; END IF;
  UPDATE public.worker_batches
  SET worker_batches_next_run_at = p_next_run_at,
      worker_batches_last_error = p_reason,
      worker_batches_updated_at = now()
  WHERE worker_batches_id = p_worker_batches_id
    AND status_id = 4;
END;
$$;

