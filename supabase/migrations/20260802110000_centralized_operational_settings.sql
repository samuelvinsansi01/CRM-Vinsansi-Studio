CREATE INDEX IF NOT EXISTS user_operational_settings_users_idx
  ON public.user_operational_settings(users_id);

ALTER TABLE public.user_operational_settings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS user_operational_settings_own_select ON public.user_operational_settings;
CREATE POLICY user_operational_settings_own_select ON public.user_operational_settings
FOR SELECT TO authenticated
USING (users_id = public.ensure_current_user());

REVOKE INSERT, UPDATE, DELETE ON public.user_operational_settings FROM anon, authenticated;
GRANT SELECT ON public.user_operational_settings TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.user_operational_settings TO service_role;

CREATE OR REPLACE FUNCTION public.ensure_user_operational_settings(p_users_id bigint DEFAULT NULL)
RETURNS public.user_operational_settings
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_users_id bigint := coalesce(p_users_id, public.ensure_current_user());
  v_row public.user_operational_settings%ROWTYPE;
BEGIN
  IF auth.role() <> 'service_role' AND v_users_id <> public.ensure_current_user() THEN
    RAISE EXCEPTION 'operational_settings_forbidden';
  END IF;

  INSERT INTO public.user_operational_settings(users_id, updated_by_auth_user_id)
  VALUES (v_users_id, auth.uid())
  ON CONFLICT (users_id) DO NOTHING;

  SELECT * INTO v_row
  FROM public.user_operational_settings
  WHERE users_id = v_users_id;

  RETURN v_row;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_user_operational_settings()
RETURNS TABLE (
  dispatch_settings jsonb,
  import_settings jsonb,
  extension_runtime_config jsonb,
  operational_timezone text,
  operational_cutoff_hour smallint,
  settings_version integer,
  updated_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_row public.user_operational_settings%ROWTYPE;
BEGIN
  v_row := public.ensure_user_operational_settings(NULL);
  RETURN QUERY SELECT
    v_row.dispatch_settings,
    v_row.import_settings,
    v_row.extension_runtime_config,
    v_row.operational_timezone,
    v_row.operational_cutoff_hour,
    v_row.settings_version,
    v_row.user_operational_settings_updated_at;
END;
$$;

CREATE OR REPLACE FUNCTION public.save_dispatch_settings(p_settings jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_users_id bigint := public.ensure_current_user();
  v_result jsonb;
BEGIN
  IF jsonb_typeof(p_settings) <> 'object'
    OR jsonb_typeof(p_settings->'whatsapp') <> 'object'
    OR jsonb_typeof(p_settings->'instagram') <> 'object'
    OR jsonb_typeof(p_settings->'chipLevels') <> 'object' THEN
    RAISE EXCEPTION 'dispatch_settings_invalid';
  END IF;

  PERFORM public.ensure_user_operational_settings(v_users_id);
  UPDATE public.user_operational_settings
  SET dispatch_settings = p_settings,
      settings_version = settings_version + 1,
      updated_by_auth_user_id = auth.uid(),
      user_operational_settings_updated_at = now()
  WHERE users_id = v_users_id
  RETURNING dispatch_settings INTO v_result;
  RETURN v_result;
END;
$$;

