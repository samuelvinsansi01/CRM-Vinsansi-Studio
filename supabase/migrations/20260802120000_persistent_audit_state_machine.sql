CREATE TABLE IF NOT EXISTS public.audit_transition_rules (
  audit_transition_rules_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type text NOT NULL CHECK (entity_type IN ('lead','queue_item')),
  from_status_id bigint NOT NULL,
  to_status_id bigint NOT NULL,
  action_key text NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(entity_type, from_status_id, to_status_id)
);

CREATE TABLE IF NOT EXISTS public.audit_events (
  audit_events_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  users_id bigint NOT NULL REFERENCES public.users(users_id) ON DELETE CASCADE,
  actor_auth_user_id uuid,
  source text NOT NULL,
  action text NOT NULL,
  entity_type text NOT NULL,
  entity_id text,
  lead_id bigint REFERENCES public.leads(leads_id) ON DELETE SET NULL,
  queue_item_id bigint REFERENCES public.queue_items(queue_items_id) ON DELETE SET NULL,
  channel_id bigint REFERENCES public.channels(channels_id) ON DELETE SET NULL,
  previous_status_id bigint,
  target_status_id bigint,
  message text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  request_id uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS audit_events_user_created_idx
  ON public.audit_events(users_id, created_at DESC, audit_events_id DESC);
CREATE INDEX IF NOT EXISTS audit_events_lead_idx
  ON public.audit_events(users_id, lead_id, created_at DESC)
  WHERE lead_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS audit_events_queue_item_idx
  ON public.audit_events(users_id, queue_item_id, created_at DESC)
  WHERE queue_item_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS audit_events_action_idx
  ON public.audit_events(users_id, action, created_at DESC);

ALTER TABLE public.audit_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit_transition_rules ENABLE ROW LEVEL SECURITY;

