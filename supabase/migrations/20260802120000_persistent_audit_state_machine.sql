CREATE OR REPLACE FUNCTION public.append_audit_event(
  p_source text,
  p_action text,
  p_entity_type text,
  p_entity_id text DEFAULT NULL,
  p_lead_id bigint DEFAULT NULL,
  p_queue_item_id bigint DEFAULT NULL,
  p_channel_id bigint DEFAULT NULL,
  p_previous_status_id bigint DEFAULT NULL,
  p_target_status_id bigint DEFAULT NULL,
  p_message text DEFAULT NULL,
  p_metadata jsonb DEFAULT '{}'::jsonb,
  p_users_id bigint DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public
AS $$
DECLARE
  v_users_id bigint;
  v_id bigint;
BEGIN
  v_users_id := CASE WHEN auth.role()='service_role' THEN p_users_id ELSE public.ensure_current_user() END;
  IF v_users_id IS NULL THEN RAISE EXCEPTION 'audit_user_required'; END IF;
  IF auth.role()<>'service_role' AND p_users_id IS NOT NULL AND p_users_id<>v_users_id THEN
    RAISE EXCEPTION 'audit_forbidden';
  END IF;
  IF nullif(trim(coalesce(p_source,'')),'') IS NULL OR nullif(trim(coalesce(p_action,'')),'') IS NULL THEN
    RAISE EXCEPTION 'audit_source_action_required';
  END IF;

  INSERT INTO public.audit_events(
    users_id, actor_auth_user_id, source, action, entity_type, entity_id,
    lead_id, queue_item_id, channel_id, previous_status_id, target_status_id,
    message, metadata
  ) VALUES (
    v_users_id, auth.uid(), trim(p_source), trim(p_action), coalesce(nullif(trim(p_entity_type),''),'system'), p_entity_id,
    p_lead_id, p_queue_item_id, p_channel_id, p_previous_status_id, p_target_status_id,
    p_message, coalesce(p_metadata,'{}'::jsonb)
  ) RETURNING audit_events_id INTO v_id;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.assert_allowed_status_transition(
  p_entity_type text,
  p_from_status_id bigint,
  p_to_status_id bigint
)
RETURNS void
LANGUAGE plpgsql
STABLE
SET search_path TO pg_catalog, public
AS $$
BEGIN
  IF p_from_status_id IS NULL OR p_to_status_id IS NULL OR p_from_status_id=p_to_status_id THEN RETURN; END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.audit_transition_rules r
    WHERE r.entity_type=p_entity_type AND r.from_status_id=p_from_status_id
      AND r.to_status_id=p_to_status_id AND r.is_active
  ) THEN
    RAISE EXCEPTION 'state_transition_not_allowed:%:%->%',p_entity_type,p_from_status_id,p_to_status_id;
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.audit_lead_state_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public
AS $$
BEGIN
  IF TG_OP='UPDATE' AND NEW.lead_status_id IS DISTINCT FROM OLD.lead_status_id THEN
    PERFORM public.assert_allowed_status_transition('lead',OLD.lead_status_id,NEW.lead_status_id);
  END IF;

  IF TG_OP='INSERT' THEN
    PERFORM public.append_audit_event('database','lead_created','lead',NEW.leads_id::text,NEW.leads_id,NULL,NEW.channels_id,NULL,NEW.lead_status_id,NULL,jsonb_build_object('origin',NEW.leads_origin),NEW.users_id);
  ELSIF NEW.lead_status_id IS DISTINCT FROM OLD.lead_status_id OR NEW.channels_id IS DISTINCT FROM OLD.channels_id THEN
    PERFORM public.append_audit_event(
      'database','lead_state_changed','lead',NEW.leads_id::text,NEW.leads_id,NULL,NEW.channels_id,
      OLD.lead_status_id,NEW.lead_status_id,NULL,
      jsonb_build_object('previous_channel_id',OLD.channels_id,'target_channel_id',NEW.channels_id),NEW.users_id
    );
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.audit_queue_item_state_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public
AS $$
BEGIN
  IF TG_OP='UPDATE' AND NEW.status_id IS DISTINCT FROM OLD.status_id THEN
    PERFORM public.assert_allowed_status_transition('queue_item',OLD.status_id,NEW.status_id);
  END IF;

  IF TG_OP='INSERT' THEN
    PERFORM public.append_audit_event('database','queue_item_created','queue_item',NEW.queue_items_id::text,NEW.leads_id,NEW.queue_items_id,NULL,NULL,NEW.status_id,NULL,jsonb_build_object('queue_id',NEW.queues_id,'position',NEW.queue_items_position),NEW.users_id);
  ELSIF NEW.status_id IS DISTINCT FROM OLD.status_id THEN
    PERFORM public.append_audit_event('database','queue_item_state_changed','queue_item',NEW.queue_items_id::text,NEW.leads_id,NEW.queue_items_id,NULL,OLD.status_id,NEW.status_id,NEW.queue_items_error_message,jsonb_build_object('attempts',NEW.queue_items_attempts),NEW.users_id);
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.audit_worker_batch_state_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO pg_catalog, public
AS $$
BEGIN
  IF TG_OP='INSERT' OR NEW.status_id IS DISTINCT FROM OLD.status_id THEN
    PERFORM public.append_audit_event(
      'worker','worker_batch_state_changed','worker_batch',NEW.worker_batches_id::text,NULL,NULL,NEW.channels_id,
      CASE WHEN TG_OP='UPDATE' THEN OLD.status_id ELSE NULL END,NEW.status_id,NEW.worker_batches_last_error,
      jsonb_build_object('chip_id',NEW.chips_id,'total',NEW.worker_batches_total_items,'processed',NEW.worker_batches_processed_items,'worker_id',NEW.worker_batches_worker_id),NEW.users_id
    );
  END IF;
  RETURN NEW;
END;
$$;

