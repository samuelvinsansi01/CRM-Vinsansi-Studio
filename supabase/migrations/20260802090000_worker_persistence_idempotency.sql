-- A migration pressupõe os catálogos canônicos:
-- status: 3=pendente, 4=processando, 5=concluído, 6=erro, 7=cancelado, 8=pausado
-- lead_status: 4=na_fila, 5=enviado

CREATE TABLE IF NOT EXISTS public.worker_batches (
  worker_batches_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  users_id bigint NOT NULL REFERENCES public.users(users_id) ON DELETE CASCADE,
  channels_id bigint NOT NULL REFERENCES public.channels(channels_id),
  chips_id bigint NOT NULL REFERENCES public.chips(chips_id) ON DELETE CASCADE,
  status_id bigint NOT NULL REFERENCES public.status(status_id),
  worker_batches_total_items integer NOT NULL DEFAULT 0 CHECK (worker_batches_total_items >= 0),
  worker_batches_processed_items integer NOT NULL DEFAULT 0 CHECK (worker_batches_processed_items >= 0),
  worker_batches_sent_items integer NOT NULL DEFAULT 0 CHECK (worker_batches_sent_items >= 0),
  worker_batches_failed_items integer NOT NULL DEFAULT 0 CHECK (worker_batches_failed_items >= 0),
  worker_batches_next_run_at timestamp with time zone,
  worker_batches_started_at timestamp with time zone,
  worker_batches_finished_at timestamp with time zone,
  worker_batches_heartbeat_at timestamp with time zone,
  worker_batches_last_error text,
  worker_batches_worker_id text,
  worker_batches_created_at timestamp with time zone NOT NULL DEFAULT now(),
  worker_batches_updated_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.worker_batch_items (
  worker_batch_items_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  users_id bigint NOT NULL REFERENCES public.users(users_id) ON DELETE CASCADE,
  worker_batches_id bigint NOT NULL REFERENCES public.worker_batches(worker_batches_id) ON DELETE CASCADE,
  queue_items_id bigint NOT NULL REFERENCES public.queue_items(queue_items_id) ON DELETE CASCADE,
  status_id bigint NOT NULL REFERENCES public.status(status_id),
  worker_batch_items_position integer NOT NULL CHECK (worker_batch_items_position > 0),
  worker_batch_items_attempts integer NOT NULL DEFAULT 0 CHECK (worker_batch_items_attempts >= 0),
  worker_batch_items_started_at timestamp with time zone,
  worker_batch_items_finished_at timestamp with time zone,
  worker_batch_items_error_message text,
  worker_batch_items_created_at timestamp with time zone NOT NULL DEFAULT now(),
  worker_batch_items_updated_at timestamp with time zone NOT NULL DEFAULT now(),
  UNIQUE (worker_batches_id, queue_items_id),
  UNIQUE (worker_batches_id, worker_batch_items_position)
);

CREATE TABLE IF NOT EXISTS public.queue_item_dispatch_parts (
  queue_item_dispatch_parts_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  users_id bigint NOT NULL REFERENCES public.users(users_id) ON DELETE CASCADE,
  queue_items_id bigint NOT NULL REFERENCES public.queue_items(queue_items_id) ON DELETE CASCADE,
  queue_item_dispatch_parts_key text NOT NULL,
  queue_item_dispatch_parts_order integer NOT NULL CHECK (queue_item_dispatch_parts_order BETWEEN 1 AND 5),
  queue_item_dispatch_parts_state text NOT NULL DEFAULT 'pending'
    CHECK (queue_item_dispatch_parts_state IN ('pending', 'processing', 'sent', 'failed', 'reconciliation_required', 'skipped')),
  queue_item_dispatch_parts_content_hash text NOT NULL,
  queue_item_dispatch_parts_body text NOT NULL DEFAULT '',
  queue_item_dispatch_parts_attempts integer NOT NULL DEFAULT 0 CHECK (queue_item_dispatch_parts_attempts >= 0),
  queue_item_dispatch_parts_claim_token uuid,
  queue_item_dispatch_parts_external_id text,
  queue_item_dispatch_parts_claimed_at timestamp with time zone,
  queue_item_dispatch_parts_sent_at timestamp with time zone,
  queue_item_dispatch_parts_error_message text,
  queue_item_dispatch_parts_created_at timestamp with time zone NOT NULL DEFAULT now(),
  queue_item_dispatch_parts_updated_at timestamp with time zone NOT NULL DEFAULT now(),
  UNIQUE (queue_items_id, queue_item_dispatch_parts_key)
);

